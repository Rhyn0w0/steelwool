package dev.steelwool.tools;

import dev.steelwool.discovery.AccessTransformers;

import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.zip.ZipFile;

/**
 * Writes {@code steelwool.accesswidener}: NeoForge's own access transformers, translated to a Fabric
 * access widener.
 *
 * <p>Arguments: the NeoForge universal jar, the output file and the vanilla Minecraft jar (the
 * classes on the class path already have the widener applied, so members are looked up in the
 * vanilla jar).
 *
 * <p>NeoForge makes some Minecraft classes and members public, and mods compiled against NeoForge
 * use them. Run by {@code ./gradlew generateNeoForgeAccessWidener}. Entries for members that only
 * NeoForge's patches add are left out.
 */
public final class GenerateNeoForgeAccessWidener {
	private static final List<String> FILES = List.of("META-INF/accesstransformer.cfg", "META-INF/accesstransformergenerated.cfg");

	public static void main(String[] args) throws IOException {
		Path neoforge = Path.of(args[0]);
		Path out = Path.of(args[1]);
		Path vanilla = Path.of(args[2]);

		if (!Files.exists(vanilla)) {
			throw new IllegalStateException("Vanilla Minecraft jar not found at " + vanilla + "; run ./gradlew build once first");
		}
		List<AccessTransformers.Entry> entries = new ArrayList<>();

		try (ZipFile zip = new ZipFile(neoforge.toFile())) {
			for (String name : FILES) {
				var entry = zip.getEntry(name);

				if (entry != null) {
					try (var reader = new InputStreamReader(zip.getInputStream(entry), StandardCharsets.UTF_8)) {
						entries.addAll(AccessTransformers.parse(reader));
					}
				}
			}
		}

		List<String> problems = new ArrayList<>();
		List<String> lines;

		try (ZipFile minecraft = new ZipFile(vanilla.toFile())) {
			lines = AccessTransformers.toAccessWidener(entries, name -> classBytes(minecraft, name), problems);
		}
		StringBuilder text = new StringBuilder();
		text.append("accessWidener v2 official\n");
		text.append("# Generated by ./gradlew generateNeoForgeAccessWidener from NeoForge ").append(neoforge.getFileName()).append(". Do not edit.\n");
		text.append("# NeoForge's access transformers, so NeoForge mods can use what NeoForge makes public.\n");
		lines.forEach(line -> text.append(line).append('\n'));
		Files.writeString(out, text.toString());
		System.out.println("Wrote " + lines.size() + " entries to " + out + "; skipped " + problems.size() + ":");
		problems.forEach(p -> System.out.println("  " + p));
	}

	private static byte[] classBytes(ZipFile minecraft, String internalName) {
		var entry = minecraft.getEntry(internalName + ".class");

		try (InputStream in = entry == null ? null : minecraft.getInputStream(entry)) {
			return in == null ? null : in.readAllBytes();
		} catch (IOException e) {
			return null;
		}
	}
}
